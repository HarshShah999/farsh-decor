function p(def: Base): Product {
  const d = defaults[def.category];
  // plank textures are square tiles; stretch them lengthwise so boards read ~1.1 m long
  const isPlank = def.category === 'flooring' && def.texture.kind === 'procedural' && def.texture.params.style !== 'parquet';
  return {
    unit: d.unit,
    textureRepeat: isPlank ? [1, 0.45] : [1, 1],
    availability: 'in-stock',
    ...def,
    specs: { ...d.specs, ...(def.specs ?? {}) },
    materialProperties: { ...d.mat, ...def.materialProperties },
  };
}

