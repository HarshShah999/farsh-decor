import type { CategoryId, MaterialProperties, Product } from '../types/catalog';

type Base = Omit<Product, 'unit' | 'textureRepeat' | 'availability' | 'specs' | 'materialProperties'> &
  Partial<Pick<Product, 'unit' | 'textureRepeat' | 'availability' | 'specs'>> & {
    materialProperties?: Partial<MaterialProperties>;
  };

